export default async function LibrarianLayout({ children }: { children: React.ReactNode }) {
  const cookieStore = await cookies()
  const token = cookieStore.get('univa_token')?.value
  if (!token) redirect('/login')
  const user = verifyToken(token)
  if (!user || user.role !== 'LIBRARIAN') redirect('/login')

  return (
    <div className="flex h-screen overflow-hidden">
      <Sidebar role={user.role} userName={user.name} collegeId={user.collegeId} navItems={navItems} />
      <main className="flex-1 overflow-y-auto bg-background p-6">{children}</main>
    </div>
  )
}
